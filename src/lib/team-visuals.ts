export function getTeamFlagUrl(teamCode: string | null) {
  if (!teamCode) return null;
  const flagCode = flagCodeByTeamCode[teamCode.toUpperCase()];
  return flagCode ? `https://flagcdn.com/${flagCode}.svg` : null;
}

export function getTeamVisualUrl(input: {
  code: string | null;
  crest: string | null;
}) {
  return getTeamFlagUrl(input.code) ?? input.crest;
}
